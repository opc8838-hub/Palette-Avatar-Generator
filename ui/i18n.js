export function translate(language, text) {
  if (language !== 'en') return text;
  if (english[text]) return english[text];
  const derived = /^(.+) · (\d{2})$/.exec(text || '');
  return derived && english[derived[1]] ? `${english[derived[1]]} · ${derived[2]}` : text;
}

